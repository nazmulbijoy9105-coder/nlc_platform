def validate_rescue_engine_output(engine_output, *, expected_company_id=None) -> frozenset[str]:
    """Reject rescue work not traceable to released, evidenced rule findings."""
    from app.rule_engine.engine import PRODUCT_SCORING_RULE_IDS, legal_score_is_released

    if not legal_score_is_released():
        raise PermissionError("Rescue generation is disabled until statutory scoring is released.")

    evaluated_company_id = getattr(engine_output, "company_id", None)
    if evaluated_company_id is None or not str(evaluated_company_id).strip():
        raise PermissionError("Rescue evaluation is missing its tenant/company identity.")
    if (
        expected_company_id is not None
        and str(evaluated_company_id) != str(expected_company_id)
    ):
        raise PermissionError("Rescue evaluation company does not match the requested tenant.")

    score = getattr(engine_output, "score_breakdown", None)
    final_score = getattr(score, "final_score", None)
    if isinstance(final_score, bool) or not isinstance(final_score, int) or not 0 <= final_score <= 100:
        raise ValueError("Rescue requires a valid released score from 0 to 100.")
    risk_value = getattr(score, "risk_band", None)
    risk_band = getattr(risk_value, "value", risk_value)
    if risk_band not in ("RED", "BLACK"):
        raise ValueError("Rescue requires a released RED or BLACK evaluation.")

    flags = getattr(engine_output, "flags", None)
    if not isinstance(flags, (list, tuple)):
        raise PermissionError("Rescue evaluation findings are missing or malformed.")

    flags_by_rule: dict[str, list[object]] = {}
    eligible: set[str] = set()
    for flag in flags:
        rule_id = getattr(flag, "rule_id", None)
        if not isinstance(rule_id, str) or not rule_id.strip():
            continue
        flags_by_rule.setdefault(rule_id, []).append(flag)

        state_value = getattr(flag, "state", None)
        state = getattr(state_value, "value", state_value)
        eval_value = getattr(flag, "eval_state", "VIOLATION")
        eval_state = getattr(eval_value, "value", eval_value)
        severity_value = getattr(flag, "severity", None)
        severity = getattr(severity_value, "value", severity_value)
        score_impact = getattr(flag, "score_impact", 0)

        if (
            getattr(flag, "resolved", None) is False
            and getattr(flag, "conditional_applies", None) is True
            and rule_id in PRODUCT_SCORING_RULE_IDS
            and state in ("NON_COMPLIANT", "VERIFIED_ABSENT")
            and eval_state == "VIOLATION"
            and severity in ("RED", "BLACK")
            and isinstance(score_impact, int)
            and not isinstance(score_impact, bool)
            and score_impact > 0
        ):
            eligible.add(rule_id)

    sequence = getattr(engine_output, "rescue_sequence", None)
    if not isinstance(sequence, list) or not sequence:
        raise ValueError("No counsel-released rescue sequence exists.")

    referenced: set[str] = set()
    for step in sequence:
        if not isinstance(step, dict):
            raise ValueError("Every rescue action must be a structured rule-linked object.")
        related = step.get("related_rules")
        if (
            not isinstance(related, list)
            or not related
            or any(not isinstance(rule_id, str) or not rule_id.strip() for rule_id in related)
        ):
            raise ValueError("Every rescue action must identify its triggering rule IDs.")
        step_rules = set(related)
        if len(step_rules) != len(related):
            raise ValueError("Rescue action contains duplicate rule references.")
        for rule_id in step_rules:
            if len(flags_by_rule.get(rule_id, [])) != 1 or rule_id not in eligible:
                raise PermissionError(
                    "Rescue action references a rule without one unique, released, "
                    "active, evidence-supported finding for this tenant."
                )
        referenced.update(step_rules)

    if not referenced:
        raise ValueError("Rescue sequence has no eligible statutory finding.")
    return frozenset(referenced)


def _derive_plan_target(explicit: date | None, steps: list) -> date | None:
    """F2a: explicit caller target wins; else the max step target; else None."""
    if explicit is not None:
        return explicit
    targets = [getattr(s, "target_completion_date", None) for s in (steps or [])]
    targets = [t for t in targets if t is not None]
    return max(targets) if targets else None  # type: ignore[type-var]


class RescueService(BaseService[RescuePlan]):
    model = RescuePlan

    # ── Rescue Plan ───────────────────────────────────────────────

    async def generate_rescue_plan(
        self,
        company_id: uuid.UUID,
        *,
        engine_output,          # EngineOutput from C_rule_engine.py
        assigned_staff_id: uuid.UUID | None = None,
        created_by: uuid.UUID | None = None,
        estimated_fee_bdt: float | None = None,
        target_completion_date: date | None = None,
        notes: str | None = None,
        engagement_id: uuid.UUID | None = None,  # RES-010
    ) -> RescuePlan:
        """
        Persist the rescue plan generated by the rule engine.
        Deactivates any previous active plan before creating the new one.
        Creates RescueStep records for all 8 steps.
        Creates Tasks from rescue steps for staff assignment.
        Triggers Engagement creation in commercial service.
        """
        # Service-level guard: callers other than the HTTP route (jobs,
        # internal services and future endpoints) must not create rescue work
        # from provisional engine output.
        from app.rule_engine.engine import legal_score_is_released
        if not legal_score_is_released():
            raise PermissionError(
                "Rescue generation is disabled until product scoring is enabled."
            )
        source_rule_ids = validate_rescue_engine_output(
            engine_output, expected_company_id=company_id
        )

        rescue_data = engine_output.rescue_sequence

        # Deactivate existing active plan
        await self.db.execute(
            update(RescuePlan)
            .where(
                RescuePlan.company_id == company_id,
                RescuePlan.is_active,
            )
            .values(is_active=False)
        )

        revenue_tier = RevenueTier.CORPORATE_RESCUE
        score = engine_output.score_breakdown.final_score
        risk_band = engine_output.score_breakdown.risk_band

        plan = await self.create(
            company_id=company_id,
            plan_name=f"Corporate Rescue Plan — {date.today().strftime('%B %Y')}",
            revenue_tier=revenue_tier,
            initial_risk_band=risk_band,
            initial_score=score,
            years_in_default=0,
            is_active=True,
            started_at=datetime.now(UTC),
            total_steps=len(rescue_data) if isinstance(rescue_data, list) else 0,
            completed_steps=0,
            blocked_steps=0,
            completion_percentage=0,
            assigned_staff_id=assigned_staff_id,
            created_by=created_by,
            engagement_id=engagement_id,
            source_rule_ids=sorted(source_rule_ids),
            quoted_fee_bdt=estimated_fee_bdt,
            target_completion_date=target_completion_date,
        )

        # Create step records
        steps = []
        total_step_count = len(rescue_data) if isinstance(rescue_data, list) else 0
        for i, step_data in enumerate(rescue_data):
            step = await self._create_step(
                plan.id, company_id, step_data, i,
                total_steps=total_step_count,
            )
            steps.append(step)

        # F2a: plan-level target - explicit caller value wins; else max
        # step target, so the PDF never shows an em-dash for Target completion.
        plan.target_completion_date = _derive_plan_target(target_completion_date, steps)
        if plan.target_completion_date is not None:
            await self.db.flush()

        # Create tasks from steps
        await self._create_tasks_from_steps(plan.id, company_id, steps, assigned_staff_id)

        # Reload with steps
        await self.db.refresh(plan)

        # Eager-load all relationships the response serializer will access.
        # Without this, accessing plan.steps / plan.company in _plan_to_response
        # triggers lazy-load IO outside an async greenlet context -> MissingGreenlet.
        from sqlalchemy.orm import selectinload
        stmt = (
            select(RescuePlan)
            .options(
                selectinload(RescuePlan.steps),
                selectinload(RescuePlan.company),
            )
            .where(RescuePlan.id == plan.id)
        )
        result = await self.db.execute(stmt)
        return result.scalar_one()

    async def _create_step(
        self,
        plan_id: uuid.UUID,
        company_id: uuid.UUID,
        step_data,
        step_index: int = 0,
        *,
        total_steps: int = 0,
    ) -> RescueStep:
        """Create a single rescue step record."""
        complexity_map = {
            "LOW": ComplexityLevel.LOW,
            "MEDIUM": ComplexityLevel.MEDIUM,
            "HIGH": ComplexityLevel.HIGH,
            "CRITICAL": ComplexityLevel.CRITICAL,
        }
        days_min = step_data.get("estimated_days_min") or step_data.get("min_days") or 7
        days_max = step_data.get("estimated_days_max") or step_data.get("max_days") or 21

        # Re-evaluation fires when ANY holds:
        #   - engine explicitly annotated triggers_reevaluation on the step
        #   - this is the final step in the plan (terminal completion)
        #   - step is CRITICAL priority (typically BLACK-override remediation)
        triggers_reevaluation = bool(
            step_data.get("triggers_reevaluation")
            or (step_index + 1) == total_steps
            or step_data.get("priority") == "CRITICAL"
        )

        step = RescueStep(
            id=uuid.uuid4(),
            rescue_plan_id=plan_id,
            company_id=company_id,
            step_number=step_index + 1,
            step_title=step_data.get("title", f"Step {step_index + 1}"),
            step_description=step_data.get("description", ""),
            statutory_basis=step_data.get("statutory_basis", None),
            complexity=complexity_map.get(
                step_data.get("complexity", "MEDIUM"),
                ComplexityLevel.MEDIUM
            ),
            estimated_days_min=days_min,
            estimated_days_max=days_max,
            target_completion_date=date.today() + timedelta(days=days_max),
            step_status=RescueStepStatus.PENDING,
            triggers_reevaluation=triggers_reevaluation,
        )
        self.db.add(step)
        await self.db.flush()
        return step

    async def _create_tasks_from_steps(
        self,
        plan_id: uuid.UUID,
        company_id: uuid.UUID,
        steps,
        assigned_to: uuid.UUID | None = None,
    ) -> None:
        """
        Create staff task records from rescue steps.
        _create_tasks_from_rescue stub implementation.
        """
        from app.models.commercial import Task
        priority_map = {
            1: TaskPriority.CRITICAL, 2: TaskPriority.CRITICAL,
            3: TaskPriority.HIGH,     4: TaskPriority.HIGH,
            5: TaskPriority.HIGH,     6: TaskPriority.MEDIUM,
            7: TaskPriority.MEDIUM,   8: TaskPriority.MEDIUM,
        }
        for step in steps:
            step_num = getattr(step, "step_number", 1)
            task = Task(
                id=uuid.uuid4(),
                company_id=company_id,
                title=f"Step {step_num}: {getattr(step, 'step_title', '')}",
                description=getattr(step, "step_description", ""),
                task_status=TaskStatus.PENDING,
                priority=priority_map.get(step_num, TaskPriority.MEDIUM),
                due_date=date.today() + timedelta(days=getattr(step, "estimated_days_max", 21)),
                assigned_to=assigned_to,
                source_rescue_step_id=step.id,
            )
            self.db.add(task)
        await self.db.flush()

    async def get_active_plan(self, company_id: uuid.UUID) -> RescuePlan | None:
        """Get the currently active rescue plan for a company."""
        from sqlalchemy.orm import selectinload
        result = await self.db.execute(
            select(RescuePlan)
            .options(selectinload(RescuePlan.steps))
            .where(
                RescuePlan.company_id == company_id,
                RescuePlan.is_active,
            )
        )
        return result.scalar_one_or_none()

    # ── Step Management ───────────────────────────────────────────

    async def update_step(
        self,
        step_id: uuid.UUID,
        *,
        status: RescueStepStatus,
        completion_notes: str | None = None,
        blocked_reason: str | None = None,
        updated_by: uuid.UUID | None = None,
    ) -> RescueStep | None:
        """
        Update rescue step status.
        COMPLETE status triggers plan progress recalculation.
        Step 8 COMPLETE triggers full compliance re-evaluation.
        """
        result = await self.db.execute(
            select(RescueStep).where(RescueStep.id == step_id)
        )
        step = result.scalar_one_or_none()
        if not step:
            return None

        updates: dict = {
            "step_status": status,
            "updated_by":  updated_by,
        }
        if status == RescueStepStatus.IN_PROGRESS:
            updates["started_at"] = datetime.now(UTC)
        elif status == RescueStepStatus.COMPLETE:
            updates["completed_at"] = datetime.now(UTC)
            updates["completion_notes"] = completion_notes
        elif status == RescueStepStatus.BLOCKED:
            updates["blocked_reason"] = blocked_reason

        for k, v in updates.items():
            if v is not None:
                setattr(step, k, v)
        self.db.add(step)
        await self.db.flush()

        # Recalculate plan progress
        await self._update_plan_progress(step.rescue_plan_id)
        return step

    async def _update_plan_progress(self, plan_id: uuid.UUID) -> None:
        """Recalculate completed_steps, blocked_steps, completion_percentage."""
        result = await self.db.execute(
            select(RescueStep).where(RescueStep.rescue_plan_id == plan_id)
        )
        all_steps = result.scalars().all()
        if not all_steps:
            return

        completed = sum(1 for s in all_steps if s.step_status == RescueStepStatus.COMPLETE)
        blocked = sum(1 for s in all_steps if s.step_status == RescueStepStatus.BLOCKED)
        total = len(all_steps)
        pct = int((completed / total) * 100) if total > 0 else 0

        await self.db.execute(
            update(RescuePlan)
            .where(RescuePlan.id == plan_id)
            .values(
                completed_steps=completed,
                blocked_steps=blocked,
                completion_percentage=pct,
                completed_at=datetime.now(UTC) if completed == total else None,
            )
        )
        await self.db.flush()

    # ── Engagement Creation from Rescue ───────────────────────────

    async def create_engagement_from_rescue(
        self,
        *,
        rescue_plan: RescuePlan,
        confirmed_fee_bdt: float,
        payment_terms: str | None = None,
    ) -> Engagement:
        """
        Explicit admin-triggered commercial engagement creation.
        Rescue-plan generation never calls this method. The supplied fee is
        recorded on the rescue plan and as the engagement's initial estimate;
        payment terms are retained in the admin-only engagement notes.
        """
        from decimal import Decimal
        from app.models.commercial import Engagement as EngagementModel
        from app.services.commercial_service import EngagementService

        if confirmed_fee_bdt <= 0:
            raise ValueError("The engagement fee must be greater than zero.")

        # Make the endpoint idempotent if the plan is already linked.
        if rescue_plan.engagement_id is not None:
            existing = await self.db.execute(
                select(EngagementModel).where(
                    EngagementModel.id == rescue_plan.engagement_id,
                    EngagementModel.company_id == rescue_plan.company_id,
                    EngagementModel.is_active.is_(True),
                )
            )
            linked = existing.scalar_one_or_none()
            if linked is not None:
                return linked
            raise ValueError("The rescue plan contains a stale engagement link.")

        fee = Decimal(str(confirmed_fee_bdt)).quantize(Decimal("0.01"))
        eng_svc = EngagementService(self.db)
        engagement = await eng_svc.create(
            company_id=rescue_plan.company_id,
            engagement_title=rescue_plan.plan_name,
            engagement_type="CORPORATE_RESCUE",
            engagement_status=EngagementStatus.IDENTIFIED,
            revenue_tier=RevenueTier.CORPORATE_RESCUE,
            complexity=ComplexityLevel.CRITICAL,
            triggered_by_risk_band=rescue_plan.initial_risk_band,
            rescue_plan_id=rescue_plan.id,
            identified_date=date.today(),
            assigned_staff_id=rescue_plan.assigned_staff_id,
            estimated_fee_bdt=fee,
            notes=(f"Payment terms: {payment_terms}" if payment_terms else None),
        )
        rescue_plan.engagement_id = engagement.id
        rescue_plan.confirmed_fee_bdt = fee
        self.db.add(rescue_plan)
        await self.db.flush()
        return engagement
