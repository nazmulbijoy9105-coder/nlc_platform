"""
Service to generate Branded PDF Compliance Reports using WeasyPrint.
"""
import asyncio
from datetime import date
from fastapi import Response
from app.services.compliance_service import ComplianceService
from app.services.company_service import CompanyService

class PDFReportService:
    def __init__(self, db):
        self.db = db

    async def generate_company_compliance_pdf(self, company_id: str) -> Response:
        company_svc = CompanyService(self.db)
        compliance_svc = ComplianceService(self.db)

        company = await company_svc.get_by_id_or_404(company_id)
        flags = await compliance_svc.get_active_flags(company_id)
        score = company.current_compliance_score or 0
        band = company.current_risk_band or "NOT_EVALUATED"

        html_content = f"""
        <html>
        <head>
            <style>
                @page {{ size: A4; margin: 2cm; }}
                body {{ font-family: 'Helvetica', sans-serif; color: #333; }}
                .header {{ text-align: center; border-bottom: 2px solid #1a365d; padding-bottom: 10px; margin-bottom: 20px; }}
                .title {{ font-size: 24px; font-weight: bold; color: #1a365d; }}
                .score-box {{ background: #f8f9fa; border: 1px solid #dee2e6; padding: 20px; text-align: center; margin: 20px 0; }}
                .score-number {{ font-size: 48px; font-weight: bold; color: {'#1a7a52' if score >= 70 else '#B91C1C' if score < 50 else '#D97706'}; }}
                .band {{ font-size: 18px; font-weight: bold; text-transform: uppercase; }}
                .flags-table {{ width: 100%; border-collapse: collapse; margin-top: 20px; }}
                .flags-table th, .flags-table td {{ border: 1px solid #dee2e6; padding: 8px; text-align: left; font-size: 12px; }}
                .flags-table th {{ background-color: #1a365d; color: white; }}
                .footer {{ margin-top: 40px; font-size: 10px; color: #6c757d; text-align: center; border-top: 1px solid #dee2e6; padding-top: 10px; }}
            </style>
        </head>
        <body>
            <div class="header">
                <div class="title">RJSC Compliance Intelligence Report</div>
                <div>Generated by Neum Lex Counsel</div>
            </div>

            <h2>{company.company_name}</h2>
            <p><strong>Registration Number:</strong> {company.registration_number}<br>
               <strong>Date of Report:</strong> {date.today().strftime('%d %B %Y')}</p>

            <div class="score-box">
                <div class="score-number">{score} / 100</div>
                <div class="band">Risk Band: {band}</div>
            </div>

            <h3>Active Compliance Flags</h3>
            <table class="flags-table">
                <tr><th>Rule ID</th><th>Severity</th><th>Description</th><th>Score Impact</th></tr>
                {''.join(f'<tr><td>{f.rule_id}</td><td>{f.severity.value}</td><td>{f.description}</td><td>-{f.score_impact} pts</td></tr>' for f in flags)}
            </table>

            <div class="footer">
                <p>This compliance intelligence output is subject to professional review under the Companies Act 1994 (Bangladesh).</p>
                <p>Automated compliance screening. Not legal advice. Consult your legal counsel.</p>
            </div>
        </body>
        </html>
        """

        from weasyprint import HTML
        pdf_bytes = await asyncio.to_thread(lambda: HTML(string=html_content).write_pdf())

        return Response(
            content=pdf_bytes,
            media_type="application/pdf",
            headers={{"Content-Disposition": f"attachment; filename=compliance_report_{company.registration_number}.pdf"}}
        )
